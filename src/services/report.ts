import type { Comparison, DesignCase, LocationInfo, OptimizationReport, SimulationResult } from '../domain/types'
import { summarize } from '../climate/service'
import { getCachedProfile } from '../climate/service'
import { resolveProfile } from '../engine/simulateService'

/* ------------------------------------------------------------------
   Report generator — assembles an engineering-style analysis report
   from actual stored models. Rendered on the Reports page and
   exportable as Markdown. Numbers come from the simulation result,
   not hand-written claims.
   ------------------------------------------------------------------ */

export interface ReportInput {
  caseData: DesignCase
  location: LocationInfo
  result: SimulationResult
  comparison: Comparison | null
  optimization: OptimizationReport | null
  materialsCatalog: { id: string; name: string }[]
}

export interface GeneratedReport {
  sections: { id: string; title: string; body: string[] }[]
  markdown: string
}

export function generateReport(input: ReportInput): GeneratedReport {
  const { caseData: c, location: loc, result: r, comparison, optimization } = input
  const profile = resolveProfile(c)
  const summary = summarize(profile.points.slice(0, c.settings.days * 24))
  const s = c.shelter
  const m = r.metrics
  const matName = (id: string) => input.materialsCatalog.find((x) => x.id === id)?.name ?? id

  const sections: { id: string; title: string; body: string[] }[] = [
    {
      id: 'scope',
      title: '1 · Design Case & Scope',
      body: [
        `Design case: ${c.name}`,
        `Generated: ${new Date().toLocaleString()}`,
        `Scope: screening-level transient thermal analysis of a single-zone shelter for the stated location, using the reduced-order RC model implemented in this prototype. This report is generated by a hackathon prototype and is NOT a certified DRDO engineering analysis.`,
      ],
    },
    {
      id: 'location',
      title: '2 · Location & Climate',
      body: [
        `Location: ${loc.name}, ${loc.region}, ${loc.country} — ${loc.lat.toFixed(2)}°, ${loc.lon.toFixed(2)}°, elevation ${loc.elevationM} m`,
        `Climate zone: ${loc.climateZone}`,
        `Climate source: ${profile.source} (${profile.kind})`,
        `Climate period: ${profile.points[0]?.t ?? '—'} → ${profile.points[Math.min(c.settings.days * 24, profile.points.length) - 1]?.t ?? '—'} (${c.settings.days}-day window, hourly resolution)`,
        `Window statistics: mean ${summary.avgTempC.toFixed(1)} °C · min ${summary.minTempC.toFixed(1)} °C · max ${summary.maxTempC.toFixed(1)} °C · mean RH ${summary.avgRH.toFixed(0)} % · mean insolation ${summary.insolationKWhM2Day.toFixed(2)} kWh/m²·day · mean wind ${summary.avgWindMs.toFixed(1)} m/s`,
      ],
    },
    {
      id: 'geometry',
      title: '3 · Shelter Geometry & Occupancy',
      body: [
        `Footprint: ${s.lengthM} m × ${s.widthM} m × ${s.heightM} m (${(s.lengthM * s.widthM).toFixed(1)} m² floor, ${(s.lengthM * s.widthM * s.heightM).toFixed(1)} m³ volume)`,
        `Shape: ${s.shape} · Orientation (principal glazing facade): ${s.orientation}`,
        `Occupancy: ${s.occupants} persons, activity “${s.activity}” + ${s.internalLoadW} W equipment`,
        `Openings: ${s.windowCount} windows totalling ${s.windowAreaM2.toFixed(1)} m², door ${s.doorAreaM2.toFixed(1)} m², infiltration/ventilation ${s.ach.toFixed(1)} ACH`,
      ],
    },
    {
      id: 'materials',
      title: '4 · Materials & Envelope',
      body: [
        `Wall: ${matName(s.wallMaterialId)}${s.insulationThicknessM > 0 ? ` + ${Math.round(s.insulationThicknessM * 1000)} mm ${matName(s.insulationMaterialId)}` : ''} — U = ${r.envelope.wall.u.toFixed(2)} W/m²K`,
        `Roof: ${matName(s.roofMaterialId)}${s.insulationThicknessM > 0 ? ` + ${Math.round(s.insulationThicknessM * 1000)} mm ${matName(s.insulationMaterialId)}` : ''} — U = ${r.envelope.roof.u.toFixed(2)} W/m²K`,
        `Floor: ${matName(s.floorMaterialId)} — U = ${r.envelope.floor.u.toFixed(2)} W/m²K (coupled to ground node)`,
        `All material properties are REFERENCE / PROTOTYPE values from public sources — not DRDO-authorized data.`,
      ],
    },
    {
      id: 'assumptions',
      title: '5 · Simulation Assumptions',
      body: [
        `Model type: single-zone transient RC heat balance, explicit Euler integration, ${c.settings.timestepMin}-min timestep.`,
        `Heat balance terms: transmitted glazing solar, absorbed opaque sol-air gains, envelope conduction (wall/roof/floor), ventilation (ACH + wind-driven infiltration), internal gains (occupants + equipment), thermal-mass storage.`,
        `Comfort criterion: prototype band ${c.settings.comfort.minC}–${c.settings.comfort.maxC} °C (configurable). PMV/PPD shown as screening indicator (Fanger form, clo = 0.9, v = 0.15 m/s, T_rad ≈ T_air).`,
        `Ground: coupled to annual-mean ambient − 2 °C. Glazing: U = 5.8, SHGC = 0.55 (reference).`,
        `LIMITATION: “Prototype / screening model — high-fidelity validation (e.g. CFD/FEA in ANSYS) required before engineering deployment.”`,
      ],
    },
    {
      id: 'results',
      title: '6 · Results — Free-Float Simulation',
      body: [
        `Average indoor temperature: ${m.avgTempInC.toFixed(1)} °C (outdoor mean ${m.avgTempOutC.toFixed(1)} °C)`,
        `Range: ${m.minTempInC.toFixed(1)} °C to ${m.maxTempInC.toFixed(1)} °C`,
        `Comfort: ${m.comfortHours} of ${m.totalHours} hours in band (${m.comfortPct.toFixed(0)} %); underheat ${m.underheatCh.toFixed(0)} °C·h, overheat ${m.overheatCh.toFixed(0)} °C·h`,
        `Mean PPD ${m.avgPpd != null ? m.avgPpd.toFixed(0) : '—'} % (screening indicator; PMV assumptions in §5)`,
      ],
    },
    {
      id: 'energy',
      title: '7 · Energy Balance & Demand',
      body: [
        `Solar gains (glazing + absorbed opaque): ${m.solarGainKWh.toFixed(1)} kWh`,
        `Conduction loss (wall/roof/openings/floor): ${m.conductionKWh.toFixed(1)} kWh`,
        `Ventilation loss: ${m.ventilationKWh.toFixed(1)} kWh`,
        `Internal gains: ${m.internalGainKWh.toFixed(1)} kWh`,
        `Estimated auxiliary thermal energy demand (ideal system holding comfort band): ${m.auxDemandKWh.toFixed(1)} kWh over the simulated window`,
        `Envelope: mean U ${m.meanU.toFixed(2)} W/m²K · effective capacity ${(m.thermalCapacity / 1e6).toFixed(2)} MJ/K`,
      ],
    },
  ]

  if (comparison) {
    const best = comparison.bestCandidateId
    sections.push({
      id: 'comparison',
      title: '8 · Design Comparison',
      body: [
        `Candidates compared: ${comparison.candidateIds.length}, all under the same climate profile and comfort settings.`,
        ...comparison.entries.slice(0, 8).map((e) => `${e.label}${e.unit ? ` [${e.unit}]` : ''}: ${e.values.map((v) => (typeof v === 'number' ? v.toFixed(e.decimals) : v)).join('  ·  ')}`),
        best ? `Leading candidate on comfort-hours: ${best} (see table for tie-breaks).` : '',
      ].filter(Boolean),
    })
  }

  if (optimization) {
    const o = optimization
    sections.push({
      id: 'optimization',
      title: '9 · Optimization Sweep',
      body: [
        `Method: constrained parameter sweep + local refinement (SciPy-style screening; no black-box AI).`,
        `Configurations evaluated: ${o.evaluated}; feasible (comfort ≥ 80 %): ${o.feasible}.`,
        `Objective: ${o.objective}`,
        `Recommended configuration: ${o.bestCandidate.name} — ${o.recommendation.headline}`,
        ...o.recommendation.reasons.map((x) => `• ${x}`),
        ...o.recommendation.tradeoffs.map((x) => `△ Trade-off: ${x}`),
      ],
    })
  }

  sections.push(
    {
      id: 'limitations',
      title: `${sections.length + 1} · Limitations`,
      body: [
        'Reduced-order single-zone model: no CFD, no multi-zone airflow, no moisture/condensation model, no radiant asymmetry.',
        'Representative/synthetic climate profiles are demonstration data; replace with authorized station records for operational use.',
        'Material properties are public reference values; DRDO-authorized datasets must replace them before design commitment.',
        'Comfort band and PMV assumptions are configurable placeholders for validation against user trials.',
        'Auxiliary energy demand assumes an ideal, 100 %-effective thermal system at the comfort bounds.',
      ],
    },
    {
      id: 'validation',
      title: `${sections.length + 2} · Validation Notes`,
      body: [
        'Determinism: identical inputs reproduce identical outputs (no stochastic terms).',
        'Sensitivity: results respond monotonically to insulation thickness, material conductivity, orientation solar gains, ventilation rate, glazing area and occupancy — verified during prototype testing.',
        'Future work: validate against ANSI/ASHRAE 140-style analytical tests, then instrumented field trials; integrate ANSYS high-fidelity workflow as an offline validation path.',
      ],
    },
  )

  const markdown = toMarkdown(c, loc, sections)
  return { sections, markdown }
}

function toMarkdown(c: DesignCase, loc: LocationInfo, sections: { id: string; title: string; body: string[] }[]): string {
  const lines: string[] = []
  lines.push(`# VAJRA — Engineering Analysis Report`)
  lines.push(``)
  lines.push(`**Design case:** ${c.name}`)
  lines.push(`**Location:** ${loc.name}, ${loc.region}, ${loc.country} (${loc.lat.toFixed(2)}°, ${loc.lon.toFixed(2)}°, ${loc.elevationM} m)`)
  lines.push(`**Generated:** ${new Date().toLocaleString()}`)
  lines.push(``)
  lines.push(`> Prototype screening analysis — not a certified engineering deliverable. Reference material properties; no DRDO-authorized data.`)
  lines.push(``)
  for (const s of sections) {
    lines.push(`## ${s.title}`)
    lines.push(``)
    for (const b of s.body) lines.push(b.startsWith('•') || b.startsWith('△') ? b : `- ${b}`)
    lines.push(``)
  }
  lines.push(`---`)
  lines.push(`Generated by VAJRA prototype (SIH 2026 · PS SIH26051 demonstration).`)
  return lines.join('\n')
}

export function downloadMarkdown(md: string, filename: string) {
  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
}
